// 繁體字筆畫數。排序用，只需要收錄功能名稱第一個字。
// 新增功能時若出現沒收錄的字，建置日誌會提醒，補一筆在這裡即可。
export const STROKES = {
  "卡": 5, "外": 5, "本": 5, "正": 5,
  "全": 6, "自": 6, "耐": 9, "多": 6,
  "快": 7, "防": 7, "足": 7, "material": 0,
  "非": 8, "抗": 7, "吸": 6, "低": 7,
  "保": 9, "重": 9, "剛": 10, "耐磨": 0,
  "透": 11, "ddd": 0,
  "絕": 12, "超": 12, "進": 12,
  "塑": 13, "腳": 13, "隔": 13, "電": 13,
  "緩": 15, "鞋": 15, "鋁": 15, "彈": 15, "複": 15,
  "鋼": 16, "輕": 14, "銅": 14, "緊": 14,
  "避": 17, "環": 17,
  "護": 20, "鐵": 21
};
export function strokeOf(name, warn) {
  const ch = (name || "").trim().charAt(0);
  if (!ch) return 99;
  if (!/[一-鿿]/.test(ch)) return 0;      // 以英數開頭的排最前
  if (ch in STROKES) return STROKES[ch];
  if (warn) warn(ch, name);
  return 98;                                       // 沒收錄的排在最後、但在空白之前
}
